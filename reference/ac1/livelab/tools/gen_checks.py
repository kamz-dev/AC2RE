"""gen_checks.py - make livelab/checks/NN.txt from the live-check rows of RE/20 (#1..N).

  py tools/gen_checks.py              (re)write the generated pages; a page without the "# generated" first line was
                                      edited by hand and is left alone
  py tools/gen_checks.py --addresses  list the code addresses the pages would probe (to verify in IDA first)

Each page shows the row's question, the port's current answer and the source. Code addresses cited in the question
become probes (max 200 logged hits each) unless listed in BAD (not an instruction start / not worth a probe).
Extra probes, fields and scripts per check come from EXTRA below.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAB = os.path.dirname(HERE)
RE20 = os.path.join(os.path.dirname(LAB), "RE", "20_stand_ins_and_live_checks.md")

ROW = re.compile(r"^\| (\d+) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|\s*$")
ADDR = re.compile(r"(?:`([A-Za-z_][\w:]*)`\s*)?(0x[0-9A-Fa-f]{6,7})\b")

# addresses that are not instruction starts or must not get an int3 (filled from the IDA check)
BAD = {0x725A3E}   # AnimSlot__FindTransition: every character, every action change (#57 uses the action column)
# verified instruction starts (IDA, 2026-10-12); per-character code is filtered to the player
WHEN = {
    0xD93C60: "[ecx+8]==$human",   # HumanGround__LedgeStop_Enter: ecx = the context, +8 its Human
    0xB23CB0: "ecx==$human",       # Human__ShouldFallOffSupport
    0xDD0B60: "[ecx+8]==$human",   # sub_DD0B60 (HumanLedge): +8 its Human
    0xE01B70: "[ecx+8]==$human",   # InAir re-entry
}

# hand-picked fields / scripts per check (fields: "name=expr:type"; see README for the expression syntax)
COMMON_FIELDS = []
EXTRA = {
    "1": {"fields": ["inair_known_haystack=[$human+0x490]+336:hex"]},   # InAir context (Human+0x490) +336
    "62": {"script": "scripts/idle_5s.txt"},
    "67": {"script": "scripts/walk_60s.txt",
           "fields": ["fidget_on=$human+0x100+0x202:u8", "breaker_timer=$hg+0x588:f32"]},   # HumanData at Human+0x100
}


def code_address(v):
    return 0x401000 <= v < 0x15A0000


def rows():
    for line in open(RE20, encoding="utf-8"):
        m = ROW.match(line.rstrip("\n"))
        if m:
            yield m.groups()


def plain(s):
    return s.replace("**", "").replace("`", "").replace("<br>", " ")


def probes_for(num, what):
    out, seen = [], set()
    for name, addr in ADDR.findall(what):
        v = int(addr, 16)
        if not code_address(v) or v in BAD or v in seen:
            continue
        seen.add(v)
        label = (name or f"p_{v:X}").replace("::", "__")[:40]
        when = f" when={WHEN[v]}" if v in WHEN else ""
        out.append(f"0x{v:X} {label}{when} max=200")
    return out


def page(num, check, what, port, source):
    lines = ["# generated by tools/gen_checks.py from RE/20 (delete this line to keep hand edits)",
             f"id: {int(num):02d}", f"title: {plain(check)}"]
    extra = EXTRA.get(num, {})
    if extra.get("script"):
        lines.append(f"script: {extra['script']}")
    lines.append("steps:")
    lines.append(f"  {plain(what)}")
    lines.append(f"  PORT NOW: {plain(port)}")
    lines.append(f"  SOURCE: {plain(source)}")
    lines.append("  F3 records, F4 marks the moment (Shift+F4: looked wrong), F2 next check.")
    pr = probes_for(num, what) + extra.get("probes", [])
    if pr:
        lines.append("probes:")
        lines += [f"  {p}" for p in pr]
    fields = COMMON_FIELDS + extra.get("fields", [])
    if fields:
        lines.append("fields:")
        lines += [f"  {f}" for f in fields]
    return "\n".join(lines) + "\n"


def main(args):
    all_rows = list(rows())
    if "--addresses" in args:
        for num, _c, what, _p, _s in all_rows:
            for p in probes_for(num, what):
                print(num, p)
        return 0
    os.makedirs(os.path.join(LAB, "checks"), exist_ok=True)
    written = kept = 0
    for num, check, what, port, source in all_rows:
        path = os.path.join(LAB, "checks", f"{int(num):02d}.txt")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                if not f.readline().startswith("# generated"):
                    kept += 1
                    continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(page(num, check, what, port, source))
        written += 1
    print(f"{written} pages written, {kept} hand-edited pages kept, from {len(all_rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
